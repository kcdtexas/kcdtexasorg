// Writes dist/_redirects (from src/data/short-links.yaml), dist/_headers and dist/sitemap.xml.
// Both Netlify and Cloudflare Pages read the first two (ADR 0010); robots.txt names the sitemap.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { parse } from 'yaml';

const DIST = 'dist';
const MODES = new Set(['follows-current', 'pinned', 'replaced-by-page', 'evergreen']);

const links = parse(readFileSync('src/data/short-links.yaml', 'utf8'));
const errors = [];
const seen = new Set();

for (const link of links) {
  const { from, to, code, mode } = link;
  if (typeof from !== 'string' || !/^\/[a-z0-9-]+$/.test(from)) errors.push(`bad "from": ${from}`);
  if (seen.has(from)) errors.push(`duplicate Short Link: ${from}`);
  seen.add(from);
  if (typeof to !== 'string' || !(to.startsWith('/') || to.startsWith('https://'))) errors.push(`${from}: "to" must be a path or https URL`);
  if (code !== 301 && code !== 302) errors.push(`${from}: code must be 301 or 302`);
  if (!MODES.has(mode)) errors.push(`${from}: unknown mode "${mode}"`);
  // A page at the same path would silently win on Netlify and lose on Cloudflare.
  for (const page of [`${DIST}${from}/index.html`, `${DIST}${from}.html`]) {
    if (mode !== 'replaced-by-page' && existsSync(page)) errors.push(`${from}: collides with ${page}`);
  }
}

if (errors.length) {
  console.error('Short Link errors:\n  ' + errors.join('\n  '));
  process.exit(1);
}

// A replaced-by-page link is dropped once its page exists.
const active = links.filter((l) => !(l.mode === 'replaced-by-page' && existsSync(`${DIST}${l.from}/index.html`)));
const redirects = active.map((l) => `${l.from}  ${l.to}  ${l.code}`).join('\n') + '\n';
writeFileSync(`${DIST}/_redirects`, `# Generated from src/data/short-links.yaml. Do not edit.\n${redirects}`);

const csp = [
  "default-src 'self'",
  "img-src 'self' data:",
  "style-src 'self'",
  "script-src 'self'",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'none'",
  "object-src 'none'",
  // No upgrade-insecure-requests: every URL here is same-origin and HSTS already
  // forces HTTPS in production, while the directive breaks plain-HTTP previews
  // (the browser rewrites every asset request to https and they all fail).
].join('; ');

const headers = `# Generated by scripts/write-host-files.mjs. Do not edit.
/*
  Strict-Transport-Security: max-age=31536000
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), browsing-topics=()

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=31536000, immutable
`;
writeFileSync(`${DIST}/_headers`, headers);

// The sitemap: every page except the 404 page, at its canonical kcdtexas.org address.
// The cards are images, not pages, so they are never listed.
const SITE = 'https://kcdtexas.org';
const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const paths = walk(DIST)
  .filter((p) => p.endsWith('.html'))
  .map((p) => '/' + relative(DIST, p).split(sep).join('/'))
  .filter((p) => p !== '/404.html')
  .map((p) => p.replace(/(^|\/)index\.html$/, '$1'))
  .sort();
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${paths.map((p) => `  <url><loc>${SITE}${p}</loc></url>`).join('\n')}
</urlset>
`;
writeFileSync(`${DIST}/sitemap.xml`, sitemap);

console.log(`Wrote ${active.length} Short Links, security headers and a sitemap of ${paths.length} pages.`);
